-- PR Card: esquema propuesto para revisar y probar en STAGING.
-- NO EJECUTAR en producción sin respaldo, pruebas de RLS y revisión de autenticación.
-- Nunca almacenar PINs ni documentos en estas tablas.

begin;

create table if not exists public.prcard_benefits (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  commerce text not null,
  title text not null,
  description text,
  redeem text,
  category text,
  valid_until_label text,
  logo_url text,
  phone text,
  social text,
  active boolean not null default true,
  featured boolean not null default false,
  sort_order integer not null default 0,
  synced_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.prcard_membership_links (
  id bigint generated always as identity primary key,
  profile_id text unique references public.profiles(id) on delete restrict,
  legacy_member_id text not null unique,
  review_status text not null default 'pending'
    check (review_status in ('pending','verified','rejected')),
  card_status text,
  expires_date date,
  verified_at timestamptz,
  synced_at timestamptz,
  created_at timestamptz not null default now(),
  constraint prcard_verified_requires_profile check (
    review_status <> 'verified' or (profile_id is not null and verified_at is not null)
  )
);

create index if not exists prcard_benefits_active_order_idx
  on public.prcard_benefits(active, sort_order, id);

alter table public.prcard_benefits enable row level security;
alter table public.prcard_membership_links enable row level security;

-- Denegación por defecto: ningún cliente web puede leer ni editar estos registros.
-- El catálogo visible deberá servirse mediante una Edge Function que compruebe
-- la identidad, el vínculo verificado y la vigencia antes de responder.
revoke all on public.prcard_benefits from anon, authenticated;
revoke all on public.prcard_membership_links from anon, authenticated;
revoke all on sequence public.prcard_benefits_id_seq from anon, authenticated;
revoke all on sequence public.prcard_membership_links_id_seq from anon, authenticated;

comment on table public.prcard_benefits is
  'Catálogo central de beneficios PR Card; acceso solo desde backend autorizado.';
comment on table public.prcard_membership_links is
  'Vínculos verificados entre perfiles PR y membresías legadas. No almacena PIN ni documento.';

commit;
