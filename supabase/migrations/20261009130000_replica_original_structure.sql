CREATE OR REPLACE VIEW public."pr_activity_summary" WITH (security_invoker=true) AS  WITH bounds AS (
         SELECT (date_trunc('week'::text, (now() AT TIME ZONE 'America/Montevideo'::text)) AT TIME ZONE 'America/Montevideo'::text) AS week_start,
            (date_trunc('month'::text, (now() AT TIME ZONE 'America/Montevideo'::text)) AT TIME ZONE 'America/Montevideo'::text) AS month_start
        )
 SELECT a.alumno_id,
    count(*) FILTER (WHERE a.fecha_inicio >= b.week_start)::integer AS actividades_semana,
    COALESCE(sum(a.distancia_metros) FILTER (WHERE a.fecha_inicio >= b.week_start), 0::numeric) / 1000.0 AS km_semana,
    COALESCE(sum(a.tiempo_movimiento_segundos) FILTER (WHERE a.fecha_inicio >= b.week_start), 0::bigint) AS segundos_semana,
    count(*) FILTER (WHERE a.fecha_inicio >= b.month_start)::integer AS actividades_mes,
    COALESCE(sum(a.distancia_metros) FILTER (WHERE a.fecha_inicio >= b.month_start), 0::numeric) / 1000.0 AS km_mes,
    COALESCE(sum(a.tiempo_movimiento_segundos) FILTER (WHERE a.fecha_inicio >= b.month_start), 0::bigint) AS segundos_mes,
    max(a.fecha_inicio) AS ultima_actividad
   FROM pr_inline_skate_activities a
     CROSS JOIN bounds b
  GROUP BY a.alumno_id;
