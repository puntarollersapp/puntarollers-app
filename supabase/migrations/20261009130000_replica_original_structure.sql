     JOIN pr_inline_skate_activities a ON a.fecha_inicio >= (c.starts_on::timestamp without time zone AT TIME ZONE 'America/Montevideo'::text) AND a.fecha_inicio < ((c.ends_on + 1)::timestamp without time zone AT TIME ZONE 'America/Montevideo'::text)
     LEFT JOIN profiles_public p ON p.id = a.alumno_id
  WHERE c.active = true AND COALESCE(a.eliminada, false) = false AND COALESCE(a.es_privada, false) = false AND COALESCE(a.visible_feed, true) = true AND lower(COALESCE(a.fuente, 'strava'::text)) = 'strava'::text
  GROUP BY c.id, c.slug, c.starts_on, c.ends_on, a.alumno_id, p.nombre, p.apellido, p.foto;
CREATE OR REPLACE VIEW public."profiles_feed" WITH (security_invoker=false) AS  SELECT id,
    nombre,
    apellido,
    foto,
    verificado,
        CASE
            WHEN fecha_nacimiento ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}'::text THEN SUBSTRING(fecha_nacimiento FROM 6 FOR 2)::integer
            ELSE NULL::integer
        END AS cumple_mes,
        CASE
            WHEN fecha_nacimiento ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}'::text THEN SUBSTRING(fecha_nacimiento FROM 9 FOR 2)::integer
            ELSE NULL::integer
        END AS cumple_dia,
    role,
    es_profesor,
    participa_como_alumno
   FROM profiles
  WHERE estado IS DISTINCT FROM 'Inactivo'::text;
CREATE OR REPLACE VIEW public."profiles_public" WITH (security_invoker=false) AS  SELECT id,
    nombre,
    apellido,
    foto,
    verificado
   FROM profiles
  WHERE estado IS DISTINCT FROM 'Inactivo'::text;

