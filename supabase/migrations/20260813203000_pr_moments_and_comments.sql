create policy "moment media owners upload" on storage.objects for insert to authenticated
with check (bucket_id = 'pr-moments' and (storage.foldername(name))[1] = pr_private.current_profile_id());
create policy "moment media visible download" on storage.objects for select to authenticated using (
  bucket_id = 'pr-moments' and exists (
    select 1 from public.pr_moments m where m.storage_path = name
  )
);
create policy "moment media owners update" on storage.objects for update to authenticated
using (bucket_id = 'pr-moments' and (storage.foldername(name))[1] = pr_private.current_profile_id())
with check (bucket_id = 'pr-moments' and (storage.foldername(name))[1] = pr_private.current_profile_id());
create policy "moment media owners delete" on storage.objects for delete to authenticated
using (bucket_id = 'pr-moments' and ((storage.foldername(name))[1] = pr_private.current_profile_id() or pr_private.is_moderator()));
